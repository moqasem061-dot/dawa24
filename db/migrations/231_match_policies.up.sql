BEGIN;

CREATE TABLE IF NOT EXISTS catalog.match_policies (
    version     TEXT PRIMARY KEY,
    body        JSONB NOT NULL,
    created_by  TEXT NOT NULL DEFAULT 'system',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE catalog.match_policies IS 'سياسات مطابقة المنتجات والحدود وإعدادات الذكاء الاصطناعي والمعرفة';
COMMENT ON COLUMN catalog.match_policies.version IS 'معرف إصدار السياسة (مثال: pm-legacy-1)';
COMMENT ON COLUMN catalog.match_policies.body IS 'نص السياسة كاملاً بصيغة JSONB';
COMMENT ON COLUMN catalog.match_policies.created_by IS 'منشئ السياسة';
COMMENT ON COLUMN catalog.match_policies.created_at IS 'تاريخ إنشاء السياسة';

-- Revoke UPDATE on match_policies to enforce immutability
REVOKE UPDATE ON catalog.match_policies FROM PUBLIC;

CREATE TABLE IF NOT EXISTS catalog.match_policy_assignments (
    workflow        TEXT NOT NULL,
    cohort          TEXT NOT NULL,
    active_version  TEXT NOT NULL REFERENCES catalog.match_policies(version),
    shadow_version  TEXT REFERENCES catalog.match_policies(version),
    changed_by      TEXT NOT NULL DEFAULT 'system',
    changed_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workflow, cohort)
);

COMMENT ON TABLE catalog.match_policy_assignments IS 'تخصيص سياسات المطابقة لكل مسار تدفق ومجموعة مستخدمين';
COMMENT ON COLUMN catalog.match_policy_assignments.workflow IS 'مسار المطابقة (vendor, savings, smartorder, catalog, compare)';
COMMENT ON COLUMN catalog.match_policy_assignments.cohort IS 'شريحة العملاء أو الكوهورت (* للكل)';
COMMENT ON COLUMN catalog.match_policy_assignments.active_version IS 'إصدار السياسة الفعّال حالياً';
COMMENT ON COLUMN catalog.match_policy_assignments.shadow_version IS 'إصدار السياسة الموازي للمقارنة (Shadow mode)';
COMMENT ON COLUMN catalog.match_policy_assignments.changed_by IS 'المسؤول عن آخر تغيير';
COMMENT ON COLUMN catalog.match_policy_assignments.changed_at IS 'تاريخ آخر تغيير';

CREATE TABLE IF NOT EXISTS catalog.match_policy_assignment_log (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow                TEXT NOT NULL,
    cohort                  TEXT NOT NULL,
    previous_active_version TEXT,
    new_active_version      TEXT NOT NULL,
    previous_shadow_version TEXT,
    new_shadow_version      TEXT,
    changed_by              TEXT NOT NULL,
    changed_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    reason                  TEXT
);

COMMENT ON TABLE catalog.match_policy_assignment_log IS 'سجل التدقيق لتغييرات تخصيص سياسات المطابقة';
COMMENT ON COLUMN catalog.match_policy_assignment_log.id IS 'المعرف التسلسلي';
COMMENT ON COLUMN catalog.match_policy_assignment_log.workflow IS 'مسار المطابقة';
COMMENT ON COLUMN catalog.match_policy_assignment_log.cohort IS 'شريحة العملاء';
COMMENT ON COLUMN catalog.match_policy_assignment_log.previous_active_version IS 'الإصدار الفعال السابق';
COMMENT ON COLUMN catalog.match_policy_assignment_log.new_active_version IS 'الإصدار الفعال الجديد';
COMMENT ON COLUMN catalog.match_policy_assignment_log.previous_shadow_version IS 'إصدار الظل السابق';
COMMENT ON COLUMN catalog.match_policy_assignment_log.new_shadow_version IS 'إصدار الظل الجديد';
COMMENT ON COLUMN catalog.match_policy_assignment_log.changed_by IS 'المسؤول عن التغيير';
COMMENT ON COLUMN catalog.match_policy_assignment_log.changed_at IS 'تاريخ التغيير';
COMMENT ON COLUMN catalog.match_policy_assignment_log.reason IS 'سبب التغيير';

