-- 240_match_ai_attempts.up.sql
--
-- Tracks granular AI matching attempts (timings, token counts, cost, outcome, compact answers).
-- Enforces tenant isolation via Row Level Security (FORCE RLS).
-- 30-day retention purged by daily worker job.

BEGIN;

CREATE TABLE IF NOT EXISTS catalog.match_ai_attempts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id              BIGINT NOT NULL REFERENCES catalog.match_runs(id) ON DELETE CASCADE,
    organization_id     BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    attempt_no          INT NOT NULL,
    kind                TEXT NOT NULL CHECK (kind IN ('proposal','retry','split','verify','audit')),
    question_count      INT NOT NULL DEFAULT 0,
    started_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    deadline_at         TIMESTAMPTZ NOT NULL,
    ended_at            TIMESTAMPTZ,
    outcome             TEXT NOT NULL CHECK (outcome IN ('ok','partial','malformed','timeout','auth','quota','unsupported','transient')),
    input_tokens        INT NOT NULL DEFAULT 0,
    output_tokens       INT NOT NULL DEFAULT 0,
    cost                NUMERIC(12,6),
    request_sha256      TEXT NOT NULL,
    invalid_excerpt     TEXT CHECK (invalid_excerpt IS NULL OR length(invalid_excerpt) <= 2048),
    answers             JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

COMMENT ON TABLE catalog.match_ai_attempts IS 'سجل محاولات الذكاء الاصطناعي للمطابقة والتوقيتات والتكاليف';
COMMENT ON COLUMN catalog.match_ai_attempts.id IS 'معرف المحاولة';
COMMENT ON COLUMN catalog.match_ai_attempts.run_id IS 'معرف عملية المطابقة التابعة لها';
COMMENT ON COLUMN catalog.match_ai_attempts.organization_id IS 'معرف المؤسسة';
COMMENT ON COLUMN catalog.match_ai_attempts.attempt_no IS 'رقم المحاولة داخل العملية';
COMMENT ON COLUMN catalog.match_ai_attempts.kind IS 'نوع المحاولة (proposal, retry, split, verify, audit)';
COMMENT ON COLUMN catalog.match_ai_attempts.question_count IS 'عدد الأسئلة في المحاولة';
COMMENT ON COLUMN catalog.match_ai_attempts.started_at IS 'تاريخ ووقت بدء المحاولة';
COMMENT ON COLUMN catalog.match_ai_attempts.deadline_at IS 'تاريخ ووقت انتهاء مهلة المحاولة';
COMMENT ON COLUMN catalog.match_ai_attempts.ended_at IS 'تاريخ ووقت انتهاء المحاولة الفعلي';
COMMENT ON COLUMN catalog.match_ai_attempts.outcome IS 'نتيجة المحاولة (ok, partial, malformed, timeout, auth, quota, unsupported, transient)';
COMMENT ON COLUMN catalog.match_ai_attempts.input_tokens IS 'عدد توكنات المدخلات';
COMMENT ON COLUMN catalog.match_ai_attempts.output_tokens IS 'عدد توكنات المخرجات';
COMMENT ON COLUMN catalog.match_ai_attempts.cost IS 'التكلفة الإجمالية للمحاولة';
COMMENT ON COLUMN catalog.match_ai_attempts.request_sha256 IS 'البصمة المشفرة للطلب';
COMMENT ON COLUMN catalog.match_ai_attempts.invalid_excerpt IS 'مقتطف من الرد غير الصالح للتشخيص بحد أقصى 2 كب';
COMMENT ON COLUMN catalog.match_ai_attempts.answers IS 'مصفوفة الإجابات المعتمدة والمدمجة بصيغة JSON';
COMMENT ON COLUMN catalog.match_ai_attempts.created_at IS 'تاريخ إنشاء السجل';

CREATE INDEX IF NOT EXISTS match_ai_attempts_run_idx ON catalog.match_ai_attempts(run_id, attempt_no);
CREATE INDEX IF NOT EXISTS match_ai_attempts_org_started_idx ON catalog.match_ai_attempts(organization_id, started_at);
CREATE INDEX IF NOT EXISTS match_ai_attempts_purge_idx ON catalog.match_ai_attempts(started_at);

ALTER TABLE catalog.match_ai_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog.match_ai_attempts FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS match_ai_attempts_tenant_isolation ON catalog.match_ai_attempts;
CREATE POLICY match_ai_attempts_tenant_isolation ON catalog.match_ai_attempts
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

COMMIT;
