-- 239_match_knowledge.up.sql
--
-- Scoped match knowledge replacing legacy decision memory (data-model §3.4, US8 T106).
-- Tracks confirmed/rejected matches, platform curated aliases and facts, with RLS tenant isolation.

BEGIN;

CREATE TABLE IF NOT EXISTS catalog.match_knowledge (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id             BIGINT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    source_namespace            TEXT NOT NULL,
    question_signature          TEXT NOT NULL,
    kind                        TEXT NOT NULL
                                CHECK (kind IN ('human_confirm','human_reject','curated_alias','curated_relationship','platform_fact','ai_answer','supplier_code')),
    target_product_id           BIGINT NULL REFERENCES catalog.products(id) ON DELETE SET NULL,
    target_granularity          TEXT NOT NULL DEFAULT 'product',
    target_fact_fingerprint     TEXT NOT NULL DEFAULT '',
    candidate_set_fingerprint   TEXT NULL,
    policy_version              TEXT NOT NULL DEFAULT '',
    normalizer_version          TEXT NOT NULL DEFAULT '',
    ai_config_id                TEXT NULL,
    prompt_version              TEXT NULL,
    display_text                TEXT NOT NULL DEFAULT '',
    status                      TEXT NOT NULL DEFAULT 'active'
                                CHECK (status IN ('active','pending_revalidation','stale','revoked')),
    legacy                      BOOLEAN NOT NULL DEFAULT false,
    created_by                  TEXT NOT NULL DEFAULT 'system',
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_by                  TEXT NULL,
    revoked_at                  TIMESTAMPTZ NULL,
    last_used_at                TIMESTAMPTZ NULL
);

COMMENT ON TABLE catalog.match_knowledge IS 'قاعدة المعرفة التراكمية لقرارات مطابقة المنتجات مع عزل المستأجرين';
COMMENT ON COLUMN catalog.match_knowledge.id IS 'المعرف الفريد لسجل المعرفة';
COMMENT ON COLUMN catalog.match_knowledge.organization_id IS 'معرف المؤسسة (أو فارغ لقرارات المنصة العامة)';
COMMENT ON COLUMN catalog.match_knowledge.source_namespace IS 'نطاق المصدر (* أو كود المورد أو النطاق المحدد)';
COMMENT ON COLUMN catalog.match_knowledge.question_signature IS 'بصمة السؤال المشتقة من الاسم والخصائص الحاسمة';
COMMENT ON COLUMN catalog.match_knowledge.kind IS 'نوع المعرفة (تأكيد بشري، رفض بشري، اسم مرادف، حقيقة منصة، إجابة ذكاء اصطناعي، إلخ)';
COMMENT ON COLUMN catalog.match_knowledge.target_product_id IS 'معرف المنتج المستهدف في الكتالوج الأساسي';
COMMENT ON COLUMN catalog.match_knowledge.target_granularity IS 'دقة المطابقة للمنتج المستهدف (product أو pack)';
COMMENT ON COLUMN catalog.match_knowledge.target_fact_fingerprint IS 'بصمة خصائص المنتج المستهدف لاكتشاف التقادم عند تغير الكتالوج';
COMMENT ON COLUMN catalog.match_knowledge.candidate_set_fingerprint IS 'بصمة مجموعة المرشحين السابقة لإجابات الذكاء الاصطناعي السلبية';
COMMENT ON COLUMN catalog.match_knowledge.policy_version IS 'إصدار السياسة التي أُنشئت المعرفة تحتها';
COMMENT ON COLUMN catalog.match_knowledge.normalizer_version IS 'إصدار المعاير المستخدم';
COMMENT ON COLUMN catalog.match_knowledge.ai_config_id IS 'معرف تهيئة الذكاء الاصطناعي المستخدم للإجابة إن وجد';
COMMENT ON COLUMN catalog.match_knowledge.prompt_version IS 'إصدار الصياغة التوجيهية للذكاء الاصطناعي إن وجد';
COMMENT ON COLUMN catalog.match_knowledge.display_text IS 'نص الإدخال المعاير للعرض في واجهات الإدارة والدعم';
COMMENT ON COLUMN catalog.match_knowledge.status IS 'حالة المعرفة (active, pending_revalidation, stale, revoked)';
COMMENT ON COLUMN catalog.match_knowledge.legacy IS 'هل تم ترحيل هذا السجل من جدول قرارات المطابقة القديم';
COMMENT ON COLUMN catalog.match_knowledge.created_by IS 'منشئ السجل (المستخدم أو النظام)';
COMMENT ON COLUMN catalog.match_knowledge.created_at IS 'تاريخ ووقت إنشاء المعرفة';
COMMENT ON COLUMN catalog.match_knowledge.revoked_by IS 'المستخدم الذي قام بإلغاء المعرفة إن وجد';
COMMENT ON COLUMN catalog.match_knowledge.revoked_at IS 'تاريخ ووقت إلغاء المعرفة';
COMMENT ON COLUMN catalog.match_knowledge.last_used_at IS 'تاريخ ووقت آخر استخدام فعال لهذه المعرفة';

-- Partial unique index ensuring active knowledge records cannot collide within the same tenant, namespace, signature, and kind
CREATE UNIQUE INDEX IF NOT EXISTS uq_match_knowledge_active
    ON catalog.match_knowledge (COALESCE(organization_id, 0), source_namespace, question_signature, kind)
    WHERE status IN ('active', 'pending_revalidation');

CREATE INDEX IF NOT EXISTS match_knowledge_sig_idx ON catalog.match_knowledge (question_signature);
CREATE INDEX IF NOT EXISTS match_knowledge_org_idx ON catalog.match_knowledge (organization_id);
CREATE INDEX IF NOT EXISTS match_knowledge_target_idx ON catalog.match_knowledge (target_product_id);
CREATE INDEX IF NOT EXISTS match_knowledge_status_idx ON catalog.match_knowledge (status);

-- Tenant Isolation via Row Level Security (RLS)
ALTER TABLE catalog.match_knowledge ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog.match_knowledge FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS match_knowledge_tenant_isolation ON catalog.match_knowledge;
CREATE POLICY match_knowledge_tenant_isolation ON catalog.match_knowledge
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

COMMIT;
