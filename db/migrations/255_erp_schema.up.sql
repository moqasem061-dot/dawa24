ALTER TABLE erp.integrations FORCE ROW LEVEL SECURITY;
CREATE POLICY integrations_tenant_isolation ON erp.integrations USING (platform.tenant_visible(organization_id)) WITH CHECK (platform.tenant_visible(organization_id));
CREATE TRIGGER integrations_touch BEFORE UPDATE ON erp.integrations FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();
