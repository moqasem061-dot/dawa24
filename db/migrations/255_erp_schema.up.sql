CREATE TABLE erp.api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    organization_id BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    integration_id BIGINT NOT NULL REFERENCES erp.integrations(id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    key_prefix TEXT NOT NULL UNIQUE CHECK (key_prefix ~ '^[a-z0-9]{8}$'),
    key_hash TEXT NOT NULL CHECK (length(key_hash) = 64),
    scopes TEXT[] NOT NULL CHECK (cardinality(scopes) >= 1),
    warehouse_id BIGINT NOT NULL REFERENCES inventory.warehouses(id),
    branch_id BIGINT NOT NULL REFERENCES org.branches(id),
    buying_user_id BIGINT REFERENCES identity.users(id) ON DELETE SET NULL,
