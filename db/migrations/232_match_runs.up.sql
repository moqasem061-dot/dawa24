-- 232_match_runs.up.sql
--
-- Tracks match run executions, state transitions, timings, counts, and AI budgets.
-- Enforces tenant isolation via Row Level Security (RLS).

BEGIN;

CREATE TABLE IF NOT EXISTS catalog.match_runs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    workflow            TEXT NOT NULL,
    entry_point         TEXT NOT NULL,
    consumer_ref        TEXT NOT NULL,
    source_revision     INT NOT NULL DEFAULT 0,
    policy_version      TEXT NOT NULL,
    catalog_revision    BIGINT NOT NULL DEFAULT 1,
    normalizer_version  TEXT NOT NULL,
    state               TEXT NOT NULL DEFAULT 'preparing'
                        CHECK (state IN ('preparing','reviewable','enhancing','committed','interrupted','failed','cancelled')),
    stage_timings       JSONB NOT NULL DEFAULT '{}'::jsonb,
    counts              JSONB NOT NULL DEFAULT '{}'::jsonb,
    ai                  JSONB NOT NULL DEFAULT '{}'::jsonb,
    heartbeat_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          TEXT NOT NULL DEFAULT 'system',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at         TIMESTAMPTZ
);

COMMENT ON TABLE catalog.match_runs IS 'عمليات مطابقة المنتجات وسجل الحالات والتوقيتات والإحصائيات';
COMMENT ON COLUMN catalog.match_runs.id IS 'معرف العملية';
COMMENT ON COLUMN catalog.match_runs.organization_id IS 'معرف المؤسسة المالكة للعملية';
COMMENT ON COLUMN catalog.match_runs.workflow IS 'مسار المطابقة (vendor, savings, smartorder, catalog, compare)';
COMMENT ON COLUMN catalog.match_runs.entry_point IS 'نقطة الدخول المسجلة';
COMMENT ON COLUMN catalog.match_runs.consumer_ref IS 'مرجع الكائن المستهلك (مثال: ingest.catalog_imports:123)';
COMMENT ON COLUMN catalog.match_runs.source_revision IS 'إصدار بيانات المصدر';
COMMENT ON COLUMN catalog.match_runs.policy_version IS 'إصدار السياسة المستخدمة';
COMMENT ON COLUMN catalog.match_runs.catalog_revision IS 'إصدار الكتالوج المركزي عند التشغيل';
COMMENT ON COLUMN catalog.match_runs.normalizer_version IS 'إصدار المعاير';
COMMENT ON COLUMN catalog.match_runs.state IS 'حالة العملية (preparing, reviewable, enhancing, committed, interrupted, failed, cancelled)';
COMMENT ON COLUMN catalog.match_runs.stage_timings IS 'توقيتات مراحل المعالجة';
COMMENT ON COLUMN catalog.match_runs.counts IS 'إحصائيات حالات القرارات الأولية';
COMMENT ON COLUMN catalog.match_runs.ai IS 'إحصائيات الذكاء الاصطناعي والتكاليف والمحاولات';
COMMENT ON COLUMN catalog.match_runs.heartbeat_at IS 'تاريخ ووقت آخر نبضة حية للعملية';
COMMENT ON COLUMN catalog.match_runs.created_by IS 'منشئ العملية';
COMMENT ON COLUMN catalog.match_runs.created_at IS 'تاريخ إنشاء العملية';
COMMENT ON COLUMN catalog.match_runs.finished_at IS 'تاريخ انتهاء العملية';

CREATE INDEX IF NOT EXISTS match_runs_org_idx ON catalog.match_runs(organization_id);
CREATE INDEX IF NOT EXISTS match_runs_consumer_ref_idx ON catalog.match_runs(consumer_ref);
CREATE INDEX IF NOT EXISTS match_runs_state_idx ON catalog.match_runs(state);
CREATE INDEX IF NOT EXISTS match_runs_heartbeat_idx ON catalog.match_runs(heartbeat_at)
    WHERE state IN ('preparing', 'enhancing');

ALTER TABLE catalog.match_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog.match_runs FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS match_runs_tenant_isolation ON catalog.match_runs;
CREATE POLICY match_runs_tenant_isolation ON catalog.match_runs
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

COMMIT;
