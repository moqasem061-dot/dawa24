-- 242_match_shadow_outcomes.up.sql
--
-- Records match decisions produced by shadow policies for comparison and evaluation.
-- Strictly tenant-isolated via FORCE RLS. Never read by operational consumer paths.

BEGIN;

CREATE TABLE IF NOT EXISTS catalog.match_shadow_outcomes (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                  BIGINT NOT NULL REFERENCES catalog.match_runs(id) ON DELETE CASCADE,
    organization_id         BIGINT NOT NULL REFERENCES org.organizations(id) ON DELETE CASCADE,
    row_ref                 TEXT NOT NULL,
    shadow_policy_version   TEXT NOT NULL REFERENCES catalog.match_policies(version) ON DELETE RESTRICT,
    decision                JSONB NOT NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT match_shadow_outcomes_run_row_policy_key UNIQUE (run_id, row_ref, shadow_policy_version)
);

COMMENT ON TABLE catalog.match_shadow_outcomes IS 'نتائج قرارات المطابقة في وضع الظل للمقارنة والتقييم';
COMMENT ON COLUMN catalog.match_shadow_outcomes.id IS 'معرف نتيجة الظل';
COMMENT ON COLUMN catalog.match_shadow_outcomes.run_id IS 'معرف عملية المطابقة';
COMMENT ON COLUMN catalog.match_shadow_outcomes.organization_id IS 'معرف المؤسسة التابعة لها العملية';
COMMENT ON COLUMN catalog.match_shadow_outcomes.row_ref IS 'مرجع الصف الأصلي للمستهلك';
COMMENT ON COLUMN catalog.match_shadow_outcomes.shadow_policy_version IS 'إصدار سياسة الظل المنفذة';
COMMENT ON COLUMN catalog.match_shadow_outcomes.decision IS 'قرار المطابقة الناتج عن سياسة الظل بصيغة JSON';
COMMENT ON COLUMN catalog.match_shadow_outcomes.created_at IS 'تاريخ إنشاء السجل';

CREATE INDEX IF NOT EXISTS match_shadow_outcomes_run_idx ON catalog.match_shadow_outcomes(run_id);
CREATE INDEX IF NOT EXISTS match_shadow_outcomes_org_idx ON catalog.match_shadow_outcomes(organization_id, created_at);
CREATE INDEX IF NOT EXISTS match_shadow_outcomes_policy_idx ON catalog.match_shadow_outcomes(shadow_policy_version);

ALTER TABLE catalog.match_shadow_outcomes ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog.match_shadow_outcomes FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS match_shadow_outcomes_tenant_isolation ON catalog.match_shadow_outcomes;
CREATE POLICY match_shadow_outcomes_tenant_isolation ON catalog.match_shadow_outcomes
    USING (platform.tenant_visible(organization_id))
    WITH CHECK (platform.tenant_visible(organization_id));

COMMIT;
