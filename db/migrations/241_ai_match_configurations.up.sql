CREATE TABLE IF NOT EXISTS catalog.ai_match_configuration_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_id   TEXT NOT NULL REFERENCES catalog.ai_match_configurations(id) ON DELETE CASCADE,
    old_status  TEXT,
    new_status  TEXT NOT NULL,
    changed_by  TEXT NOT NULL,
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    reason      TEXT
);

