package erp

import "errors"

type Error struct {
	Code    string
	Status  int
	Details map[string]any
}

func (e *Error) Error() string { return e.Code }
func NewError(code string, status int, details map[string]any) *Error {
	return &Error{Code: code, Status: status, Details: details}
}

