package matching

import (
	"time"

	"github.com/moqasem061-dot/dawa24/internal/shared/matchflow"
	"github.com/moqasem061-dot/dawa24/internal/shared/productmatch"
)

// PolicyRecord represents a versioned matching policy (data-model §3.5).
type PolicyRecord struct {
	Version   string              `json:"version"`
	Body      productmatch.Policy `json:"body"`
	CreatedBy string              `json:"created_by"`
	CreatedAt time.Time           `json:"created_at"`
}

// PolicyAssignment maps a workflow and cohort to an active and optional shadow policy (data-model §3.5).
type PolicyAssignment struct {
	Workflow      string    `json:"workflow"`
	Cohort        string    `json:"cohort"`
	ActiveVersion string    `json:"active_version"`
	ShadowVersion *string   `json:"shadow_version,omitempty"`
	ChangedBy     string    `json:"changed_by"`
	ChangedAt     time.Time `json:"changed_at"`
}

// PolicyAssignmentLog tracks audit changes to policy assignments (data-model §3.5, US13 T152).
type PolicyAssignmentLog struct {
	ID                    int64     `json:"id"`
	Workflow              string    `json:"workflow"`
	Cohort                string    `json:"cohort"`
	PreviousActiveVersion *string   `json:"previous_active_version,omitempty"`
	NewActiveVersion      string    `json:"new_active_version"`
	PreviousShadowVersion *string   `json:"previous_shadow_version,omitempty"`
	NewShadowVersion      *string   `json:"new_shadow_version,omitempty"`
	ChangedBy             string    `json:"changed_by"`
	ChangedAt             time.Time `json:"changed_at"`
	Reason                *string   `json:"reason,omitempty"`
}

// ShadowOutcome records a decision generated by a shadow policy (data-model §3.9, US13 T150-T151).
type ShadowOutcome struct {
	ID                  int64                 `json:"id"`
	RunID               int64                 `json:"run_id"`
	OrganizationID      int64                 `json:"organization_id"`
	RowRef              string                `json:"row_ref"`
	ShadowPolicyVersion string                `json:"shadow_policy_version"`
	Decision            matchflow.RowDecision `json:"decision"`
	CreatedAt           time.Time             `json:"created_at"`
}
