package productmatch

import "testing"

func TestExpandShorthand(t *testing.T) {
	cases := []struct{ in, want string }{
		{"كونكور 5مج 30ق", "كونكور 5مج 30 قرص"},
		{"نيكسيوم 40مج 14ك", "نيكسيوم 40مج 14 كبسولة"},
		{"اكنلوفيكس 20 مج 20 ك", "اكنلوفيكس 20 مج 20 كبسولة"},
		{"ابراميون 100مجم زجاجة ش", "ابراميون 100مجم زجاجة شراب"},
		{"ادفيل 2ش", "ادفيل 2 شريط"},
		{"سيفترياكسون 1جم 1ف", "سيفترياكسون 1جم 1 فيال"},
		{"فيتامين ك امبول", "فيتامين ك امبول"},
		{"بتنوفيت ان كريم", "بتنوفيت ان كريم"},
		{"٣٠ق بروفين", "30 قرص بروفين"},
		{"بانادول اكسترا", "بانادول اكسترا"},
		{"امكسيل 500ملجم ف", "امكسيل 500ملجم فيال"},
		{"الفيوزوشين 10ملجم ك ممتد المفعول", "الفيوزوشين 10ملجم كبسولة ممتد المفعول"},
		{"ايدريسين 50مجم/25مل ف وريد", "ايدريسين 50مجم/25مل فيال وريد"},
	}
	for _, c := range cases {
		if got := ExpandShorthand(c.in); got != c.want {
			t.Errorf("ExpandShorthand(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}
